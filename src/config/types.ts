import type { AssetId } from "./assets";

export type Language = "en" | "id";
export type TreatmentCategory = "massage" | "reflexology" | "body-care" | "recovery" | "relaxation";
export type TreatmentId = "full-body-massage" | "swedish-massage" | "deep-tissue-massage" | "aromatherapy-massage" | "reflexology" | "hot-stone-massage" | "sports-massage" | "body-scrub" | "head-neck-shoulder" | "couples-massage" | "pregnancy-massage";
export type TherapistId = "maya" | "sarah" | "dina" | "rina";
export type Provenance = Readonly<{ isDemo: boolean; isVerified: boolean; dataSource: "demo" | "owner" }>;
export type TreatmentOption = Readonly<{ minutes: number; price: number }>;
export type Treatment = Provenance & Readonly<{
  id: TreatmentId;
  category: TreatmentCategory;
  categories: readonly TreatmentCategory[];
  visual: AssetId;
  recommendedMinutes: number;
  popular: boolean;
  options: readonly TreatmentOption[];
}>;
export type CoverageStatus = "available" | "limited" | "coming-soon" | "unavailable";
export type ServiceArea = Provenance & Readonly<{ id: string; name: string; parentId?: string; status: CoverageStatus }>;
export type Therapist = Provenance & Readonly<{
  id: TherapistId;
  name: string;
  experience: number;
  rating: number;
  sessions: number;
  treatments: readonly TreatmentId[];
  status: "request" | "limited";
  visual: AssetId;
}>;
export type Testimonial = Provenance & Readonly<{ id: "review-one" | "review-two" | "review-three"; name: string; rating: number; treatment: TreatmentId; date: string }>;
export type TherapistPreference = "" | "male" | "female" | "specific";
export type Promotion = Provenance & Readonly<{ id: "welcome"; percentage: number; enabled: boolean }>;
export type BusinessConfig = Readonly<{
  brand: string;
  currency: string;
  locale: string;
  timeZone: string;
  timeZoneLabel: string;
  pricingMode: "demonstration" | "live";
  whatsappNumber: string | null;
  contactEmail: string | null;
  contactPhone: string | null;
  siteUrl: string | null;
  serviceAreas: readonly ServiceArea[];
  operatingHours: readonly string[];
  therapistPreferences: readonly TherapistPreference[];
  treatments: readonly Treatment[];
  therapists: readonly Therapist[];
  testimonials: readonly Testimonial[];
  promotions: readonly Promotion[];
  policyLinks: readonly Readonly<{ label: Readonly<Record<Language, string>>; href: string }>[];
}>;
export type BookingDraft = {
  fullName: string;
  cityId: string;
  treatmentId: string;
  durationMinutes: string;
  date: string;
  time: string;
  address: string;
  therapistPreference: TherapistPreference;
  therapistId: string;
  notes: string;
  consent: boolean;
};
export type BookingSelection = Partial<Pick<BookingDraft, "cityId" | "treatmentId" | "durationMinutes" | "therapistId" | "therapistPreference">>;
export type BookingErrorCode = "nameRequired" | "nameLong" | "addressRequired" | "addressLong" | "notesLong" | "cityRequired" | "cityUnavailable" | "treatmentRequired" | "durationRequired" | "consentRequired" | "preferenceInvalid" | "therapistInvalid" | "dateInvalid" | "datePast" | "timeInvalid" | "timePast" | "slotUnavailable" | "timezoneInvalid";
export type BookingErrors = Partial<Record<keyof BookingDraft, BookingErrorCode>>;
export type ValidatedBooking = Readonly<{
  fullName: string;
  city: ServiceArea;
  treatment: Treatment;
  option: TreatmentOption;
  date: string;
  time: string;
  address: string;
  therapistPreference: TherapistPreference;
  therapist?: Therapist;
  notes: string;
  consent: true;
}>;
export type BookingValidation = { valid: false; errors: BookingErrors } | { valid: true; booking: ValidatedBooking };
